// Writes data/media.generated.ts with the intrinsic size and dominant colour of
// every image in public/media, so next/image never needs to guess.
//   node scripts/media/manifest.mjs
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const MEDIA = path.join(ROOT, "public/media");
const OUT = path.join(ROOT, "data/media.generated.ts");

const entries = [];
for (const folder of ["site", "stock"]) {
  const dir = path.join(MEDIA, folder);
  const files = (await fs.readdir(dir)).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort();
  for (const file of files) {
    const full = path.join(dir, file);
    const { width, height } = await sharp(full).metadata();
    const { dominant } = await sharp(full).stats();
    const hex = `#${[dominant.r, dominant.g, dominant.b].map((v) => v.toString(16).padStart(2, "0")).join("")}`;
    entries.push({ key: `${folder}/${file.replace(/\.[a-z]+$/i, "")}`, src: `/media/${folder}/${file}`, width, height, color: hex });
  }
}

const body = entries
  .map((e) => `  "${e.key}": { src: "${e.src}", width: ${e.width}, height: ${e.height}, color: "${e.color}" },`)
  .join("\n");

await fs.writeFile(
  OUT,
  `// Generated by scripts/media/manifest.mjs — do not edit by hand.\n\nexport const mediaManifest = {\n${body}\n} as const;\n\nexport type MediaKey = keyof typeof mediaManifest;\n`,
);
console.log(`wrote ${entries.length} entries to ${path.relative(ROOT, OUT)}`);
